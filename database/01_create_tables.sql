-- Installation script for a new, empty schema. Do not run against existing app tables.
-- =====================================================
-- SUPPORT DESK
-- TABLE CREATION SCRIPT
-- =====================================================


-- 1. Departments
CREATE TABLE ts_departments (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY
         CONSTRAINT pk_ts_departments PRIMARY KEY,

    name VARCHAR2(75) NOT NULL,

    CONSTRAINT uq_ts_departments_name
        UNIQUE (name)
);


-- 2. Users
CREATE TABLE ts_users (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY
               CONSTRAINT pk_ts_users PRIMARY KEY,

    first_name VARCHAR2(100) NOT NULL,
    last_name  VARCHAR2(100) NOT NULL,
    email      VARCHAR2(255) NOT NULL,
    role       VARCHAR2(50) DEFAULT 'Employee' NOT NULL,
    created_at DATE DEFAULT SYSDATE NOT NULL,
    dept_id    NUMBER,
    password_hash VARCHAR2(100),

    CONSTRAINT uq_ts_users_email
        UNIQUE (email),

    CONSTRAINT chk_ts_users_role
        CHECK (
            role IN (
                'Employee',
                'Support',
                'Admin'
            )
        ),

    CONSTRAINT fk_ts_users_department
        FOREIGN KEY (dept_id)
        REFERENCES ts_departments(id)
);


-- 3. Ticket Categories
CREATE TABLE ts_categories (
    id   NUMBER GENERATED BY DEFAULT AS IDENTITY
         CONSTRAINT pk_ts_categories PRIMARY KEY,

    name VARCHAR2(100) NOT NULL,

    CONSTRAINT uq_ts_categories_name
        UNIQUE (name)
);


-- 4. Tickets
CREATE TABLE ts_tickets (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY
                 CONSTRAINT pk_ts_tickets PRIMARY KEY,

    title        VARCHAR2(150) NOT NULL,
    description  CLOB NOT NULL,

    priority     VARCHAR2(10) DEFAULT 'Medium' NOT NULL,
    status       VARCHAR2(50) DEFAULT 'Unassigned' NOT NULL,

    created_at   DATE DEFAULT SYSDATE NOT NULL,
    resolved_at  DATE,

    submitted_by NUMBER NOT NULL,
    assigned_to  NUMBER,
    category_id  NUMBER NOT NULL,
    resolution_notes VARCHAR2(250),

    CONSTRAINT chk_ts_tickets_priority
        CHECK (
            priority IN (
                'Low',
                'Medium',
                'High',
                'Critical'
            )
        ),

    CONSTRAINT chk_ts_tickets_status
        CHECK (
            status IN (
                'Unassigned',
                'Assigned',
                'Pending',
                'In Progress',
                'Resolved',
                'Reopened',
                'Closed',
                'Cancelled'
            )
        ),

    CONSTRAINT chk_ts_tickets_resolved_date
        CHECK (
            resolved_at IS NULL
            OR resolved_at >= created_at
        ),

    CONSTRAINT fk_ts_tickets_category
        FOREIGN KEY (category_id)
        REFERENCES ts_categories(id),

    CONSTRAINT fk_ts_tickets_submitter
        FOREIGN KEY (submitted_by)
        REFERENCES ts_users(id),

    CONSTRAINT fk_ts_tickets_assignee
        FOREIGN KEY (assigned_to)
        REFERENCES ts_users(id)
);


-- 5. Ticket Comments
CREATE TABLE ts_ticket_comments (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY
               CONSTRAINT pk_ts_ticket_comments PRIMARY KEY,

    comment_text VARCHAR2(1000) NOT NULL,
    created_at   DATE DEFAULT SYSDATE NOT NULL,
    ticket_id    NUMBER NOT NULL,
    user_id      NUMBER NOT NULL,

    CONSTRAINT fk_ts_comments_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES ts_tickets(id),

    CONSTRAINT fk_ts_comments_user
        FOREIGN KEY (user_id)
        REFERENCES ts_users(id)
);


-- 6. Ticket Status History
CREATE TABLE ts_status_history (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY
                CONSTRAINT pk_ts_status_history PRIMARY KEY,

    old_status  VARCHAR2(50),
    new_status  VARCHAR2(50) NOT NULL,
    changed_at  DATE DEFAULT SYSDATE NOT NULL,
    changed_by  NUMBER NOT NULL,
    ticket_id   NUMBER NOT NULL,

    CONSTRAINT chk_ts_history_old_status
        CHECK (
            old_status IS NULL
            OR old_status IN (
                'Unassigned',
                'Assigned',
                'Pending',
                'In Progress',
                'Resolved',
                'Reopened',
                'Closed',
                'Cancelled'
            )
        ),

    CONSTRAINT chk_ts_history_new_status
        CHECK (
            new_status IN (
                'Unassigned',
                'Assigned',
                'Pending',
                'In Progress',
                'Resolved',
                'Reopened',
                'Closed',
                'Cancelled'
            )
        ),

    CONSTRAINT fk_ts_history_user
        FOREIGN KEY (changed_by)
        REFERENCES ts_users(id),

    CONSTRAINT fk_ts_history_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES ts_tickets(id)
);
